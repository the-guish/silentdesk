#!/usr/bin/env sh
# Writes Sources/SilentDeskCore/Adapters/Migrations.swift from the shared
# migrations in spec/sql, so the core carries the schema it was built with.
# SilentDeskCoreTests fails when the two drift apart.
set -eu

core="$(cd "$(dirname "$0")/.." && pwd)"
sql="$core/../../spec/sql"
out="$core/Sources/SilentDeskCore/Adapters/Migrations.swift"

{
    echo "// Generated by Scripts/sync-migrations.sh from spec/sql. Do not edit."
    echo ""
    echo "/// The shared schema, as numbered migrations (docs/specs/storage.md)."
    echo "enum Migrations {"
    echo "    struct Migration: Sendable {"
    echo "        let number: Int"
    echo "        let name: String"
    echo "        let sql: String"
    echo "    }"
    echo ""
    echo "    static let all: [Migration] = ["
    for file in "$sql"/*.sql; do
        name="$(basename "$file" .sql)"
        number="$(printf '%s' "$name" | cut -d_ -f1 | sed 's/^0*//')"
        echo "        Migration("
        echo "            number: $number,"
        echo "            name: \"$name\","
        echo "            sql: #\"\"\""
        cat "$file"
        echo "\"\"\"#"
        echo "        ),"
    done
    echo "    ]"
    echo "}"
} > "$out"
echo "Wrote $out"
